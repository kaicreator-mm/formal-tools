#!/usr/bin/env bash
# One-off: patch the UNPACKED why3 shim with rm -rf guard (the archived shim predates
# the hardening), then re-verify why3 in-place. Root container writes, host verify.
set -euo pipefail
docker run --rm \
  -v /home/cc/formal-tools-build/src/portable/builders/tools/why3.sh:/spec.sh:ro \
  -v /home/cc/formal-tools-build/out/evidence/r2/unpack/tools/why3:/t \
  ft-builder:deb13 python3 - <<'PYEOF'
import re

spec = open("/spec.sh", encoding="utf-8").read()
m = re.search(r"ft::make_shim '(.*?)'\n", spec, re.S)
shim_body = m.group(1)
shim = (
    "#!/bin/sh\n"
    "# generated by formal-tools portable builders - do not edit\n"
    'FT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)\n'
    'TOOL_DIR="$FT_ROOT/tools/why3"\n'
    + shim_body
    + "\n"
)
open("/t/run", "w", encoding="utf-8", newline="\n").write(shim)
import os
os.chmod("/t/run", 0o755)
print("SHIM_PATCHED bytes=", len(shim))
PYEOF
cd /home/cc/formal-tools-build
rm -f out/evidence/r2/verify-why3.tsv out/evidence/r2/why3/verify-why3.*.log 2>/dev/null || true
SKIP_AB=1 bash src/portable/scripts/r2-verify-loop.sh > r2-why3-only2.log 2>&1
grep -E "why3 ->" r2-why3-only2.log | tail -1
cd out/evidence/r2/why3 && grep verdict verify-why3.tsv | tail -1
