#!/usr/bin/env python3
"""R2 final: atomically fix why3 shim + fc symlink, re-tar both archives, re-extract
both into the unpack tree, re-verify why3 + fast-check. All inside ONE root container."""
import os
import re
import shutil
import subprocess
import sys

OUT = "/out"
SRC = "/src"
B = os.path.join(OUT, "bundle", "formal-tools-portable-debian13-x86_64")
PKG = os.path.join(OUT, "packages")
UNPACK = os.path.join(OUT, "evidence", "r2", "unpack")
TOOL = "why3"

def sh(cmd):
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    print(r.stdout[-400:] if r.stdout else "", r.stderr[-300:] if r.stderr else "")
    if r.returncode != 0:
        print("CMD FAIL:", cmd[:150])
        sys.exit(1)
    return r.stdout

# 1) regen why3 shim from CURRENT spec (has rm -rf guard)
spec = open(os.path.join(SRC, "portable", "builders", "tools", f"{TOOL}.sh"), encoding="utf-8").read()
m = re.search(r"ft::make_shim '(.*?)'\n", spec, re.S)
shim_body = m.group(1)
shim = (
    "#!/bin/sh\n"
    "# generated by formal-tools portable builders - do not edit\n"
    'FT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)\n'
    f'TOOL_DIR="$FT_ROOT/tools/{TOOL}"\n'
    + shim_body
    + "\n"
)
open(os.path.join(OUT, "tools", TOOL, "run"), "w", encoding="utf-8", newline="\n").write(shim)
os.chmod(os.path.join(OUT, "tools", TOOL, "run"), 0o755)
print("1 shim regenerated WITH guard:", "rm -rf" in shim_body)

# 2) refresh bundle/tools/why3 + tests/fast-check symlink
bdir = os.path.join(B, "tools", TOOL)
if os.path.exists(bdir):
    shutil.rmtree(bdir)
shutil.copytree(os.path.join(OUT, "tools", TOOL), bdir, symlinks=True)
subprocess.run(["chmod", "-R", "a+rX", bdir], check=True)
fcdir = os.path.join(B, "tests", "fast-check")
os.makedirs(fcdir, exist_ok=True)
lnk = os.path.join(fcdir, "node_modules")
if os.path.islink(lnk) or os.path.exists(lnk):
    os.remove(lnk)
os.symlink("../../tools/fast-check/node_modules", lnk)
print("2 bundle refreshed (tools/why3 + fc symlink)")

# 3) re-tar the why3 archive from bundle
ar = os.path.join(PKG, "tools", f"{TOOL}-1.8.0-linux-x86_64.tar.zst")
if os.path.exists(ar):
    os.remove(ar)
r = subprocess.run(
    f"cd {B} && tar -cf - 'tools/{TOOL}' | zstd --ultra -22 -T16 -q -f -o {ar}",
    shell=True, capture_output=True, text=True)
if r.returncode != 0:
    print("TAR FAIL:", r.stderr[-200:])
    sys.exit(1)
print("3 why3 archive re-tarred", os.path.getsize(ar) // 1048576, "MB")

# 4) re-extract why3 into the unpack tree (complete: usr/bin + usr/lib + usr/share)
updir = os.path.join(UNPACK, "tools", TOOL)
if os.path.exists(updir):
    shutil.rmtree(updir)
os.makedirs(updir)
import tarfile
with tarfile.open(ar) as tf:
    tf.extractall(UNPACK)
subprocess.run(["chmod", "-R", "a+rX", updir], check=True)
print("4 unpack refreshed")
