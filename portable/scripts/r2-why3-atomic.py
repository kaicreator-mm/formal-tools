#!/usr/bin/env python3
"""R2 why3 atomic final: regenerate shim, rebuild bundle/tools/why3, re-tar archive,
re-extract into unpack tree, then verify why3 (single tool). Runs as root container."""
import os
import re
import shutil
import subprocess
import tarfile

OUT = "/out"
SRC = "/src"
B = os.path.join(OUT, "bundle", "formal-tools-portable-debian13-x86_64")
PKG = os.path.join(OUT, "packages")
UNPACK = os.path.join(OUT, "evidence", "r2", "unpack")
TOOL = "why3"

spec = open(os.path.join(SRC, "portable", "builders", "tools", f"{TOOL}.sh"), encoding="utf-8").read()
m = re.search(r"ft::make_shim '(.*?)'\n", spec, re.S)
shim_body = m.group(1)
shim = (
    "#!/bin/sh\n"
    "# generated by formal-tools portable builders - do not edit\n"
    'FT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)\n'
    f'TOOL_DIR="$FT_ROOT/tools/{TOOL}"\n'
    + shim_body
    + "\n"
)

# 1) write shim into out/tools
run_p = os.path.join(OUT, "tools", TOOL, "run")
open(run_p, "w", encoding="utf-8", newline="\n").write(shim)
os.chmod(run_p, 0o755)
print("1 shim written")

# 2) refresh bundle/tools/why3
bdir = os.path.join(B, "tools", TOOL)
if os.path.exists(bdir):
    shutil.rmtree(bdir)
shutil.copytree(os.path.join(OUT, "tools", TOOL), bdir, symlinks=True)
subprocess.run(["chmod", "-R", "a+rX", bdir], check=True)
print("2 bundle refreshed")

# 3) re-tar the why3 archive from bundle
ar = os.path.join(PKG, "tools", f"{TOOL}-1.8.0-linux-x86_64.tar.zst")
if os.path.exists(ar):
    os.remove(ar)
r = subprocess.run(
    f"cd {B} && tar -cf - 'tools/{TOOL}' | zstd --ultra -22 -T16 -q -f -o {ar}",
    shell=True, check=True)
print("3 archive re-tarred", os.path.getsize(ar) // 1048576, "MB")

# 4) re-extract into the unpack tree (fresh + complete)
updir = os.path.join(UNPACK, "tools", TOOL)
if os.path.exists(updir):
    shutil.rmtree(updir)
os.makedirs(updir)
r2 = subprocess.run(
    f"zstd -dc {ar} | tar -xf - -C {updir}", shell=True, check=True)
subprocess.run(["chmod", "-R", "a+rX", updir], check=True)
print("4 unpack refreshed, usr/bin/why3 exists:", os.path.isfile(os.path.join(updir, "usr/bin/why3")))

# 5) update archive sha line in SHA256SUMS
import hashlib
h = hashlib.sha256(open(ar, "rb").read()).hexdigest()
sums_p = os.path.join(PKG, "SHA256SUMS")
lines = [l for l in open(sums_p, encoding="utf-8").read().splitlines() if "tools/why3" not in l]
lines.append(f"{h}  tools/{TOOL}-1.8.0-linux-x86_64.tar.zst")
lines.sort(key=lambda l: l.split("  ", 1)[1])
open(sums_p, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("5 sums updated")
