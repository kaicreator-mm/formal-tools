#!/usr/bin/env bash
# R2 final: atomic why3+fast-check repair (root container), then single-tool verifies.
set -euo pipefail
docker run --rm \
  -v /home/cc/formal-tools-build/out:/out \
  -v /home/cc/formal-tools-build/src:/src:ro \
  -v /home/cc/formal-tools-build/src/portable/scripts/r2-final-why3-fc.py:/final.py \
  ft-builder:deb13 python3 /final.py
cd /home/cc/formal-tools-build
# refresh bundle/tools/why3 from out/tools (post-shim-regen), re-tar why3 archive
docker run --rm \
  -v /home/cc/formal-tools-build/out:/out \
  -v /home/cc/formal-tools-build/src/portable/builders/tools/why3.sh:/spec.sh:ro \
  ft-builder:deb13 python3 - <<'PYEOF'
import os, re
spec = open("/spec.sh", encoding="utf-8").read()
m = re.search(r"ft::make_shim '(.*?)'\n", spec, re.S)
body = m.group(1)
shim = (
    "#!/bin/sh\n"
    "# generated by formal-tools portable builders - do not edit\n"
    'FT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)\n'
    'TOOL_DIR="$FT_ROOT/tools/why3"\n'
    + body + "\n"
)
open("/out/tools/why3/run", "w", encoding="utf-8", newline="\n").write(shim)
os.chmod("/out/tools/why3/run", 0o755)
print("SHIM_PATCHED")
PYEOF
cd /home/cc/formal-tools-build/out/bundle/formal-tools-portable-debian13-x86_64
rm -f /home/cc/formal-tools-build/out/packages/tools/why3-1.8.0-linux-x86_64.tar.zst
tar -cf - tools/why3 | zstd --ultra -22 -T16 -q -f -o /home/cc/formal-tools-build/out/packages/tools/why3-1.8.0-linux-x86_64.tar.zst
zstd -t /home/cc/formal-tools-build/out/packages/tools/why3-1.8.0-linux-x86_64.tar.zst
echo WHY3_ARCHIVE_OK
cd /home/cc/formal-tools-build
rm -f out/evidence/r2/verify-why3.tsv out/evidence/r2/why3/verify-why3.*.log out/evidence/r2/verify-fast-check.tsv out/evidence/r2/fast-check/verify-fast-check.*.log 2>/dev/null || true
SKIP_AB=1 bash src/portable/scripts/r2-verify-loop.sh > r2-why3-fc-final.log 2>&1
grep -E "why3 ->|fast-check ->" r2-why3-fc-final.log | tail -2
